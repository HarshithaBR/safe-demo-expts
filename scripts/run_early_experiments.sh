#!/usr/bin/env bash
set -u
set -o pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
export MAMBA_ROOT_PREFIX="${MAMBA_ROOT_PREFIX:-/home/ubuntu/micromamba}"
eval "$(${MICROMAMBA_BIN:-$HOME/bin/micromamba} shell hook -s bash 2>/dev/null || /tmp/bin/micromamba shell hook -s bash)"
micromamba activate safe311
export PYTHONPATH="$ROOT"
export MUJOCO_GL="${MUJOCO_GL:-glfw}"
PYTHON="${PYTHON:-python}"
LOG=results/queue/early_experiments.log
mkdir -p results/queue results/checkpoints_ft results/gated_recovery

ts() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }
log() { echo "[$(ts)] $*" | tee -a "$LOG"; }

log "==== early experiments begin ===="

log "START A1c C_hist"
if $PYTHON -m safe_demo_expts.scripts.run_s1_gated_recovery --policies C_hist \
    --out results/s1_gated_recovery_C_hist.json >>"$LOG" 2>&1; then
  log "DONE A1c C_hist"
else
  log "FAIL A1c C_hist"
fi

log "START A1c C_nohist"
if $PYTHON -m safe_demo_expts.scripts.run_s1_gated_recovery --policies C_nohist \
    --out results/s1_gated_recovery_C_nohist.json >>"$LOG" 2>&1; then
  log "DONE A1c C_nohist"
else
  log "FAIL A1c C_nohist"
fi

log "START interventions V1-V4 full (freeze deploy, all policies)"
if $PYTHON -m safe_demo_expts.scripts.run_s1_interventions \
    --out results/s1_interventions_escape.json >>"$LOG" 2>&1; then
  log "DONE interventions"
else
  log "FAIL interventions"
fi

log "START mini-DAgger full"
if $PYTHON -m safe_demo_expts.scripts.run_s1_minidagger \
    --out results/s1_minidagger.json >>"$LOG" 2>&1; then
  log "DONE mini-DAgger"
else
  log "FAIL mini-DAgger"
fi

log "START mini-DAgger safe (oracle-only, lr=1e-4, 10 ep)"
if $PYTHON -m safe_demo_expts.scripts.run_s1_minidagger --safe \
    --out results/s1_minidagger_safe.json >>"$LOG" 2>&1; then
  log "DONE mini-DAgger safe"
else
  log "FAIL mini-DAgger safe"
fi

# Prefer queue-produced budget curves; otherwise run here once step6 finishes or failed
if [[ -f results/s1_ablations_done.flag ]] && [[ -f results/s1_budget_curves.json ]]; then
  log "SKIP budget curves — already regenerated by paper queue"
else
  log "WAIT for paper-queue step6 budget curves (or run ourselves if queue done)"
  # If mpc/budget still running, don't duplicate; only run if queue fully exited without flag
  if ! pgrep -f 'run_s1_budget_curves|run_s1_mpc_harden|run_all_paper_queue' >/dev/null 2>&1; then
    log "START budget curves"
    if $PYTHON -m safe_demo_expts.scripts.run_s1_budget_curves \
        --out results/s1_budget_curves.json >>"$LOG" 2>&1; then
      log "DONE budget curves"
    else
      log "FAIL budget curves"
    fi
  else
    log "SKIP budget curves — paper queue still owns that job"
  fi
fi

log "==== early experiments finished ===="
echo OK > results/queue/EARLY_EXPERIMENTS_COMPLETE
